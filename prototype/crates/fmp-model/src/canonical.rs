//! Canonical JSON and the digests built on it.
//!
//! `01_contract.md` §12 and `07_definition_format.md` §6 define one canonical
//! form: keys sorted by code point, no insignificant whitespace, UTF-8 without a
//! BOM, integers only, no trailing newline, no duplicate keys.
//!
//! The encoding below is checked against Python's
//! `json.dumps(..., sort_keys=True, separators=(",", ":"), ensure_ascii=False)`
//! in `canonical_form_matches_python`, because `tools/check_definition.py` uses
//! that call to print the definition digest. Two implementations that disagree
//! on escaping would produce two digests for one definition.

use sha2::{Digest, Sha256};

use crate::json::Json;

/// The canonical bytes of a parsed document.
pub fn canonical_bytes(value: &Json) -> Vec<u8> {
    let mut out = Vec::new();
    write_value(value, &mut out);
    out
}

/// `sha256:<hex>` over the canonical bytes of `value`.
pub fn canonical_digest(value: &Json) -> String {
    let bytes = canonical_bytes(value);
    sha256_prefixed(&[&bytes])
}

/// Lowercase hex SHA-256 over the concatenation of `parts`.
pub fn sha256(parts: &[&[u8]]) -> String {
    let mut hasher = Sha256::new();
    for part in parts {
        hasher.update(part);
    }
    hex(&hasher.finalize())
}

/// `sha256:<hex>` over the concatenation of `parts`.
pub fn sha256_prefixed(parts: &[&[u8]]) -> String {
    format!("sha256:{}", sha256(parts))
}

fn hex(bytes: &[u8]) -> String {
    let mut out = String::with_capacity(bytes.len() * 2);
    for byte in bytes {
        out.push(nibble(byte >> 4));
        out.push(nibble(byte & 0x0F));
    }
    out
}

fn nibble(value: u8) -> char {
    match value {
        0..=9 => (b'0' + value) as char,
        _ => (b'a' + value - 10) as char,
    }
}

fn write_value(value: &Json, out: &mut Vec<u8>) {
    match value {
        Json::Null => out.extend_from_slice(b"null"),
        Json::Bool(true) => out.extend_from_slice(b"true"),
        Json::Bool(false) => out.extend_from_slice(b"false"),
        Json::Int(number) => out.extend_from_slice(number.to_string().as_bytes()),
        Json::Str(text) => write_string(text, out),
        Json::Array(items) => {
            out.push(b'[');
            for (index, item) in items.iter().enumerate() {
                if index > 0 {
                    out.push(b',');
                }
                write_value(item, out);
            }
            out.push(b']');
        }
        Json::Object(entries) => {
            let mut sorted: Vec<&(String, Json)> = entries.iter().collect();
            // `String` orders by UTF-8 bytes, which is code-point order for
            // valid UTF-8, which is what §12 asks for and what Python does.
            sorted.sort_by(|a, b| a.0.cmp(&b.0));
            out.push(b'{');
            for (index, (key, item)) in sorted.iter().enumerate() {
                if index > 0 {
                    out.push(b',');
                }
                write_string(key, out);
                out.push(b':');
                write_value(item, out);
            }
            out.push(b'}');
        }
    }
}

pub(crate) fn write_string(text: &str, out: &mut Vec<u8>) {
    out.push(b'"');
    for ch in text.chars() {
        match ch {
            '"' => out.extend_from_slice(b"\\\""),
            '\\' => out.extend_from_slice(b"\\\\"),
            '\n' => out.extend_from_slice(b"\\n"),
            '\r' => out.extend_from_slice(b"\\r"),
            '\t' => out.extend_from_slice(b"\\t"),
            '\u{8}' => out.extend_from_slice(b"\\b"),
            '\u{c}' => out.extend_from_slice(b"\\f"),
            control if (control as u32) < 0x20 => {
                out.extend_from_slice(format!("\\u{:04x}", control as u32).as_bytes());
            }
            other => {
                let mut buffer = [0u8; 4];
                out.extend_from_slice(other.encode_utf8(&mut buffer).as_bytes());
            }
        }
    }
    out.push(b'"');
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::json;

    /// Generated by Python 3.8:
    ///
    /// ```text
    /// json.dumps(value, sort_keys=True, separators=(",", ":"),
    ///            ensure_ascii=False).encode("utf-8")
    /// ```
    ///
    /// One case per escaping decision: a control character, a quote, a
    /// backslash, a non-ASCII scalar, an empty object, and key order.
    #[test]
    fn canonical_form_matches_python() {
        let cases: &[(&str, &str)] = &[
            (r#"{"b":1,"a":2}"#, r#"{"a":2,"b":1}"#),
            (r#"{"k":"a\"b\\c"}"#, r#"{"k":"a\"b\\c"}"#),
            (r#"{"k":"\u0001\u001f"}"#, r#"{"k":"\u0001\u001f"}"#),
            (r#"{"k":"\n\t\r\b\f"}"#, r#"{"k":"\n\t\r\b\f"}"#),
            (r#"{"k":"é😀"}"#, r#"{"k":"é😀"}"#),
            (r#"{"k":{}}"#, r#"{"k":{}}"#),
            (r#"{"k":[]}"#, r#"{"k":[]}"#),
            (r#"{"Z":1,"a":2}"#, r#"{"Z":1,"a":2}"#),
        ];
        for (input, expected) in cases {
            let value = json::parse(input.as_bytes()).unwrap();
            let bytes = canonical_bytes(&value);
            assert_eq!(
                std::str::from_utf8(&bytes).unwrap(),
                *expected,
                "input {input}"
            );
        }
    }

    #[test]
    fn rejects_a_slash_escape_difference() {
        // A slash is never escaped by either implementation; this guards
        // against a "helpful" escaping pass being added later.
        let value = json::parse(br#"{"k":"a/b"}"#).unwrap();
        assert_eq!(
            std::str::from_utf8(&canonical_bytes(&value)).unwrap(),
            r#"{"k":"a/b"}"#
        );
    }

    #[test]
    fn digest_is_prefixed_hex() {
        let value = json::parse(b"{}").unwrap();
        let digest = canonical_digest(&value);
        assert!(digest.starts_with("sha256:"));
        assert_eq!(digest.len(), 7 + 64);
    }

    #[test]
    fn empty_object_vector() {
        // sha256("{}") measured with Python:
        // hashlib.sha256(b"{}").hexdigest()
        //   44136fa355b3678a1146ad16f7e8649e94fb4fc21fe77e8310c060f61caaff8a
        let value = json::parse(b"{}").unwrap();
        assert_eq!(
            canonical_digest(&value),
            "sha256:44136fa355b3678a1146ad16f7e8649e94fb4fc21fe77e8310c060f61caaff8a"
        );
    }
}
